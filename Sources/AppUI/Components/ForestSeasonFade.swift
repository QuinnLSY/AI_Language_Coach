import SwiftUI

// MARK: - 换季的交叉淡入淡出（#636）

/// 季节装饰层的出场 / 退场：**只淡不挪**。
///
/// 换季动的是一整片林子，两件事必须同时发生，缺一件就还是「闪一下」：
/// 1. **配色插值** —— 山丘 / 树冠 / 草坡一起渐变。由挂在根上的
///    `.appAnimation(.scene, value: state.theme.season)` 负责（见 `MainView`）；
/// 2. **装饰层交替** —— 风筝换成雁阵、草地换成雪地。就是这里这一个修饰符：
///    它是 `if theme.season == .xxx { … }` 分支里那只组件的过渡。
///
/// ⚠️ **只做不透明度**：这些层的位置由地形函数定死（草尖 / 天空 / 树冠 /
/// 坡面），任何位移或缩放都会让它看起来像是从别处飞进来的。
///
/// ⚠️ 两段是**一对**：只写这一半（根上没挂 `.scene` 动画）时，分支的
/// 插拔不落在任何带动画的事务里，照样是瞬跳；只写那一半（层上没有过渡）
/// 时，配色会渐变而装饰层仍然凭空出现。`ForestSeasonWiringTests` 两头都钉。
public extension View {

    func seasonFade() -> some View {
        transition(.opacity)
    }
}
